/** 决定这场的对战组合（玩家操作主队）。要在创建画面与比赛之前调用 */
export function setMatchup(awayId, homeId) {
  const find = (id) => TEAMS.find((t) => t.id === id);
  const h = find(homeId) || TEAMS[1];
  let a = find(awayId) || TEAMS[0];
  if (a === h) a = TEAMS.find((t) => t !== h);
  GAME.away = { ...a, side: 'AWAY', sideTc: '客队', kit: a.kits.away };
  GAME.home = { ...h, side: 'HOME', sideTc: '主队', kit: h.kits.home };
  return GAME;
}
